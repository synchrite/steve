"""Original hand-placed 16-bit sprite. Light enters from upper left.
Run with Python and Pillow from any directory. Dots are transparent.
Every map character represents exactly one output pixel; no scaling.
"""
from pathlib import Path
from PIL import Image

SIZE = (20, 44)
PALETTE = {'o': '#303345', 's': '#9c6657', 't': '#ce977c', 'h': '#edbaa0', 'l': '#ffdac0', 'a': '#252b37', 'b': '#424052', 'c': '#6b6173', 'd': '#b4a1b0', 'j': '#344f71', 'J': '#557ba1', 'L': '#8cacc8', 'x': '#242d42', 'g': '#cfb581', 'r': '#9a466c', 'R': '#e286a7'}
PIXELS = """
....oooo............
...orRRRo...........
...oRRRro...........
...orRRro...........
....orrroooo........
....orRRRRRro.......
...orRRRRrrro.......
...orRRRrhhhho......
...orRRrhhhhho......
...orRrhdododo......
....orrhdododoho....
....orhhhhohhlhho...
....oshhhhhhhhlo....
.....oshhhhhtoo.....
......oshhtto.......
....oabhtthbo.......
...oaJLbbbJbao......
...obJLbbbJbbao.....
...obJLbbbJbbao.....
...obJLbbbJbbao.....
...obJLJJJJbbao.....
...obJJggJJbbao.....
...obJJJJJJbbao.....
...obJJLLJJbbao.....
...obJJJjJJbbao.....
...obJJJjJJbbao.....
...ohJJjjJJhhto.....
...ohJJJJJJhhlo.....
...otJJJJJJthto.....
...ooJJJJJJooo......
....ojJJJJJjo.......
....ojJLJJJjo.......
....ojJLjjJjo.......
....ojJJoojJo.......
....ojJjo.ojJo......
....ojJjo.ojJo......
....ojJjo.ojJo......
....ojJjo.ojJo......
....ojJjo.ojJo......
....ojJjo.ojJo......
....oxxxo.oxxo......
....oxgxo.oxgxo.....
....oxxxxooxxxxo....
....oooooooooooo....
""".strip().splitlines()

assert len(PIXELS) == SIZE[1]
assert all(len(row) == SIZE[0] for row in PIXELS)
image = Image.new("RGBA", SIZE, (0, 0, 0, 0))
for y, row in enumerate(PIXELS):
    for x, symbol in enumerate(row):
        if symbol != ".":
            color = PALETTE[symbol].lstrip("#")
            image.putpixel((x, y), tuple(int(color[i:i+2], 16) for i in (0, 2, 4)) + (255,))
output = Path(__file__).resolve().parents[2] / "assets" / "wife.png"
image.save(output)
with Image.open(output) as check:
    assert check.size == SIZE
    assert set(check.getchannel("A").getdata()) <= {0, 255}
    box = check.getbbox()
    assert box[3] == SIZE[1], "Empty rows beneath anchor"
    assert abs(box[0] - (SIZE[0] - box[2])) <= 1, "Unbalanced anchor"
    assert len(check.getcolors()) <= 17
print(f"{output.name}: {SIZE}, binary alpha, balanced bottom anchor verified")
