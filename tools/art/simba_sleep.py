"""Original hand-placed 16-bit sprite. Light enters from upper left.
Run with Python and Pillow from any directory. Dots are transparent.
Every map character represents exactly one output pixel; no scaling.
"""
from pathlib import Path
from PIL import Image

SIZE = (56, 24)
PALETTE = {'o': '#493528', 's': '#805335', 'd': '#a87340', 't': '#c98f4e', 'h': '#dfa960', 'l': '#efd099', 'm': '#302d2b', 'n': '#56504a', 'e': '#9b642f', 'w': '#fff0cf', 'p': '#776080', 'v': '#b6a0c6', 'b': '#b6ce4c', 'k': '#6e8338'}
PIXELS = """
....................oooooooooooo........................
................oooohhhhhhhhhttttoooo...................
.............ooohhhhhhhhhhhhhhttttdooo..................
...........oohhhhhhttttttttttttttddooo..................
.........oohhhhttttttttttttttttttdddoo..................
........ohhhttttttttttttttttttttttdddo..................
.......ohhtttttttttttttttttttttttttdddo.................
......ohhttttttttttttttttttttttttttdddo.................
.....ohhttttttttttttttttttttttttttttdddo................
.....ohttttttttttttttttttttttttttttttdddoo..............
....ohhttttttttttttttttttttttttddddddddddoo.............
....ohtttttttttttttttttttttddddddppvptttttooo...........
....ohttttttttttttttttttddddddppvvpvtttttttddoo.........
....otttttttttttttttttdddddddpvvpvtttttttttttdoo........
....otttttttttttttttdddddddpvpvvpvtttttttttttttso.......
....otttttttttttttdddddddoopvvpvttttooottttttttnmmo.....
.....otttttttttttdddddddoo.opvpvttttttttttttttnnmmmo....
.....otttttttttddddddddo...opvttttttttttttttnnnmmmmo....
......otttttttddddddddo....otttttttttttttttnnnnmmmmo....
.......otttttdddddddooooooooottllllttttttttnnnmmmmo.....
........otttddddddoohhhhtttttttlllllltttttttddoo........
.........otddddddoohhhtttttttlllllllltttttdddoo.........
..........oottttttttttttttttllllllllllttdddoo...........
............ooooooooooooooooooooooooooooooo.............
""".strip().splitlines()

assert len(PIXELS) == SIZE[1]
assert all(len(row) == SIZE[0] for row in PIXELS)
image = Image.new("RGBA", SIZE, (0, 0, 0, 0))
for y, row in enumerate(PIXELS):
    for x, symbol in enumerate(row):
        if symbol != ".":
            color = PALETTE[symbol].lstrip("#")
            image.putpixel((x, y), tuple(int(color[i:i+2], 16) for i in (0, 2, 4)) + (255,))
output = Path(__file__).resolve().parents[2] / "assets" / "simba_sleep.png"
image.save(output)
with Image.open(output) as check:
    assert check.size == SIZE
    assert set(check.getchannel("A").getdata()) <= {0, 255}
    box = check.getbbox()
    assert box[3] == SIZE[1], "Empty rows beneath anchor"
    assert abs(box[0] - (SIZE[0] - box[2])) <= 1, "Unbalanced anchor"
    assert len(check.getcolors()) <= 17
print(f"{output.name}: {SIZE}, binary alpha, balanced bottom anchor verified")
