"""Original hand-placed 16-bit sprite. Light enters from upper left.
Run with Python and Pillow from any directory. Dots are transparent.
Every map character represents exactly one output pixel; no scaling.
"""
from pathlib import Path
from PIL import Image

SIZE = (20, 44)
PALETTE = {'o': '#303743', 's': '#754d38', 't': '#bb8560', 'h': '#e5b28a', 'l': '#f6cf9e', 'a': '#343b29', 'b': '#535d39', 'c': '#7b8150', 'd': '#a1a46a', 'j': '#324c6a', 'J': '#506f91', 'L': '#7c99b1', 'x': '#222a37', 'g': '#aab7b5', 'r': '#76533b', 'R': '#a47b50'}
PIXELS = """
.....oooooo.........
....orRRRrro........
...orRRRrrrro.......
...orRrrrrrro.......
...orrrrrhhho.......
...orrrhhhhho.......
...orrrhhhohho......
....orhhhhhohho.....
....orhhhhhhlhho....
....orhhhhhhhllo....
.....oshhhhhsso.....
.....oshhhsssso.....
......oshhssoo......
.....oabthhto.......
....oabccbbbo.......
...obccbbccbao......
...obccbbccbbao.....
...obccbbccbbbo.....
...obccbbccbbbo.....
...obccbbccbbbo.....
...obccbbacbbbo.....
...obccbbabbbbo.....
...obccbbabbbbo.....
...obccbbabccbo.....
...obbcbbaabcbo.....
...obbcbbaabcbo.....
...obbcbbaahhto.....
...obbcbbaahhlo.....
...oabbbbaathto.....
...oaabbbaaooo......
...ojJJJJJJjo.......
...ojJLJJJJjo.......
...ojJLJjjJjo.......
...ojJJjoojJo.......
...ojJJjo.ojJo......
...ojJJjo.ojJo......
...ojJJjo.ojJo......
...ojJJjo.ojJo......
...ojJJjo.ojJo......
...ojJJjo.ojJo......
...oxxxxo.oxxo......
...oxggxo.oxgxo.....
...oxxxxxooxxxxo....
...ooooooooooooo....
""".strip().splitlines()

assert len(PIXELS) == SIZE[1]
assert all(len(row) == SIZE[0] for row in PIXELS)
image = Image.new("RGBA", SIZE, (0, 0, 0, 0))
for y, row in enumerate(PIXELS):
    for x, symbol in enumerate(row):
        if symbol != ".":
            color = PALETTE[symbol].lstrip("#")
            image.putpixel((x, y), tuple(int(color[i:i+2], 16) for i in (0, 2, 4)) + (255,))
output = Path(__file__).resolve().parents[2] / "assets" / "steve_walk.png"
image.save(output)
with Image.open(output) as check:
    assert check.size == SIZE
    assert set(check.getchannel("A").getdata()) <= {0, 255}
    box = check.getbbox()
    assert box[3] == SIZE[1], "Empty rows beneath anchor"
    assert abs(box[0] - (SIZE[0] - box[2])) <= 1, "Unbalanced anchor"
    assert len(check.getcolors()) <= 17
print(f"{output.name}: {SIZE}, binary alpha, balanced bottom anchor verified")
